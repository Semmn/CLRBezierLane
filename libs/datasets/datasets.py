"""TuSimple, LLAMAS and CurveLanes datasets for the official CLRerNet (mmdet 3.x).

All three subclass the official ``CulaneDataset`` and only override annotation
parsing, label/mask loading and (for CurveLanes) the per-resolution crop. The
augmentation (``albumentation``) and CLR target generation
(``PackCLRNetInputs``) are the official ones.

Annotation handling follows:
    TuSimple   CLRNet  clrnet/datasets/tusimple.py
    LLAMAS     CLRNet  clrnet/datasets/llamas.py (seg masks drawn as CLRNet does)
    CurveLanes CLRerNet features/curvelane libs/datasets/curvelanes_dataset.py
"""
import json
import os
import os.path as osp
import pickle
from multiprocessing import Pool
from pathlib import Path

import cv2
import numpy as np
from mmdet.registry import DATASETS

from libs.datasets.culane_dataset import CulaneDataset

from .common import lanes_to_clrernet_points
from .metrics import llamas_utils


class _GTRoundTripMixin:
    """``results_with_labels`` builds the pre-pipeline dict for any split
    (used by tools/clrbezier/probe_datasets.py for GT round-trip checks)."""

    def load_gt_lanes(self, idx):  # pragma: no cover - overridden
        raise NotImplementedError

    def results_with_labels(self, idx):
        imgname = str(Path(self.img_prefix).joinpath(self.img_infos[idx]))
        img = cv2.imread(imgname)
        kps, id_classes, id_instances = lanes_to_clrernet_points(self.load_gt_lanes(idx))
        return dict(filename=imgname, sub_img_name=self.img_infos[idx], img=img,
                    gt_points=kps, id_classes=id_classes, id_instances=id_instances,
                    img_shape=img.shape, ori_shape=img.shape)


# =============================================================================
# TuSimple (CLRNet)
# =============================================================================
TUSIMPLE_SPLIT_FILES = {
    "trainval": ["label_data_0313.json", "label_data_0601.json", "label_data_0531.json"],
    "train": ["label_data_0313.json", "label_data_0601.json"],
    "val": ["label_data_0531.json"],
    "test": ["test_label.json"],
}


@DATASETS.register_module()
class TusimpleDataset(_GTRoundTripMixin, CulaneDataset):
    """Args:
        data_root: TuSimple root containing the label json files, ``clips/`` and
            ``seg_label/`` (generated by CLRNet ``tools/generate_seg_tusimple.py``).
        split: trainval | train | val | test.
    """

    def __init__(self, data_root, split, pipeline, test_mode=True, **kwargs):
        if split not in TUSIMPLE_SPLIT_FILES:
            raise ValueError(f"Unknown TuSimple split {split!r}; use {sorted(TUSIMPLE_SPLIT_FILES)}")
        kwargs.pop("data_list", None)
        kwargs.pop("diff_file", None)
        self.split = split
        super().__init__(data_root=data_root, data_list=split, pipeline=pipeline,
                         diff_file=None, test_mode=test_mode, **kwargs)

    def parse_datalist(self, split):
        img_infos, annotations, mask_paths = [], [], []
        for anno_file in TUSIMPLE_SPLIT_FILES[split]:
            with open(osp.join(self.img_prefix, anno_file), "r") as anno_obj:
                for line in anno_obj:
                    if not line.strip():
                        continue
                    data = json.loads(line)
                    y_samples = data["h_samples"]
                    # CLRNet TuSimple.load_annotations
                    lanes = [[(x, y) for (x, y) in zip(lane, y_samples) if x >= 0]
                             for lane in data["lanes"]]
                    lanes = [lane for lane in lanes if len(lane) > 0]
                    img_infos.append(data["raw_file"])
                    annotations.append(lanes)
                    mask_paths.append(data["raw_file"].replace("clips", "seg_label")[:-3] + "png")
        return img_infos, annotations, mask_paths

    def load_gt_lanes(self, idx):
        return self.annotations[idx]

    def load_labels(self, idx):
        return lanes_to_clrernet_points(self.load_gt_lanes(idx))

    def load_mask(self, idx):
        # CLRNet BaseDataset: first channel of the seg_label png.
        mask = cv2.imread(str(Path(self.img_prefix).joinpath(self.mask_paths[idx])),
                          cv2.IMREAD_UNCHANGED)
        if mask is None:
            raise FileNotFoundError(f"TuSimple seg label not found: {self.mask_paths[idx]}")
        if mask.ndim > 2:
            mask = mask[:, :, 0]
        return mask.squeeze()


# =============================================================================
# LLAMAS (CLRNet)
# =============================================================================
LLAMAS_SPLIT_DIRECTORIES = {"train": "labels/train", "val": "labels/valid"}
LLAMAS_TEST_IMGS_DIR = "color_images/test"
LLAMAS_IMG_H, LLAMAS_IMG_W = 717, 1276


def _parse_llamas_json(json_path):
    """CLRNet LLAMAS.load_annotations for one label file."""
    lanes = llamas_utils.get_horizontal_values_for_four_lanes(json_path)
    lanes = [[(x, y) for x, y in zip(lane, range(LLAMAS_IMG_H)) if x >= 0] for lane in lanes]
    lanes = [lane for lane in lanes if len(lane) > 0]
    lanes = [list(set(lane)) for lane in lanes]  # remove duplicated points
    lanes = [lane for lane in lanes if len(lane) > 2]  # remove lanes with less than 2 points
    lanes = [sorted(lane, key=lambda x: x[1]) for lane in lanes]  # sort by y
    lanes.sort(key=lambda lane: lane[0][0])
    return lanes


@DATASETS.register_module()
class LlamasDataset(_GTRoundTripMixin, CulaneDataset):
    """Args:
        data_root: LLAMAS root with ``color_images/`` and ``labels/``.
        split: train | val | test (test labels are not public).
        cache_dir: annotation cache (parsing 58k json files is slow).
        num_workers: processes used for the first parse.
        seg_thickness: CLRNet draws seg masks with thickness 15.
    """

    def __init__(self, data_root, split, pipeline, test_mode=True, cache_dir="cache",
                 num_workers=8, seg_thickness=15, **kwargs):
        if split != "test" and split not in LLAMAS_SPLIT_DIRECTORIES:
            raise ValueError(f"Unknown LLAMAS split {split!r}; use train | val | test")
        kwargs.pop("data_list", None)
        kwargs.pop("diff_file", None)
        self.split = split
        self.cache_dir = cache_dir
        self.num_workers = int(num_workers)
        self.seg_thickness = int(seg_thickness)
        super().__init__(data_root=data_root, data_list=split, pipeline=pipeline,
                         diff_file=None, test_mode=test_mode, **kwargs)

    @staticmethod
    def json_to_img_path(json_path):
        # CLRNet LLAMAS.get_img_path
        base_name = "/".join(json_path.split("/")[-3:])
        return osp.join("color_images", base_name.replace(".json", "_color_rect.png"))

    def parse_datalist(self, split):
        if split == "test":
            imgs_dir = osp.join(self.img_prefix, LLAMAS_TEST_IMGS_DIR)
            img_infos = sorted(
                osp.join(LLAMAS_TEST_IMGS_DIR, osp.relpath(osp.join(root, f), imgs_dir))
                for root, _, files in os.walk(imgs_dir) for f in files if f.endswith(".png"))
            return img_infos, [[] for _ in img_infos], [None for _ in img_infos]

        labels_dir = osp.join(self.img_prefix, LLAMAS_SPLIT_DIRECTORIES[split])
        import hashlib
        root_key = hashlib.md5(osp.abspath(self.img_prefix).encode()).hexdigest()[:10]
        cache_path = osp.join(self.cache_dir, f"llamas_{split}_{root_key}_lanedata.pkl")
        if osp.exists(cache_path):
            with open(cache_path, "rb") as f:
                cached = pickle.load(f)
            return cached["img_infos"], cached["annotations"], cached["mask_paths"]

        json_paths = sorted(osp.join(root, f) for root, _, files in os.walk(labels_dir)
                            for f in files if f.endswith(".json"))
        print(f"[LlamasDataset] parsing {len(json_paths)} annotations (cached afterwards)...")
        if self.num_workers > 1:
            with Pool(self.num_workers) as pool:
                annotations = pool.map(_parse_llamas_json, json_paths, chunksize=64)
        else:
            annotations = [_parse_llamas_json(p) for p in json_paths]
        img_infos = [self.json_to_img_path(p) for p in json_paths]
        mask_paths = [osp.relpath(p, self.img_prefix) for p in json_paths]  # key only
        os.makedirs(self.cache_dir, exist_ok=True)
        with open(cache_path, "wb") as f:
            pickle.dump(dict(img_infos=img_infos, annotations=annotations, mask_paths=mask_paths), f)
        return img_infos, annotations, mask_paths

    def load_gt_lanes(self, idx):
        return self.annotations[idx]

    def load_labels(self, idx):
        return lanes_to_clrernet_points(self.load_gt_lanes(idx))

    def load_mask(self, idx):
        """CLRNet LLAMAS seg label, drawn in memory instead of written next to labels."""
        seg = np.zeros((LLAMAS_IMG_H, LLAMAS_IMG_W, 3))
        for i, lane in enumerate(self.load_gt_lanes(idx)):
            for j in range(0, len(lane) - 1):
                cv2.line(seg, (round(lane[j][0]), lane[j][1]),
                         (round(lane[j + 1][0]), lane[j + 1][1]),
                         (i + 1, i + 1, i + 1), thickness=self.seg_thickness)
        # CLRNet writes the float image to png and reads channel 0 back as uint8.
        return seg[:, :, 0].astype(np.uint8)


# =============================================================================
# CurveLanes (CLRerNet features/curvelane)
# =============================================================================
CURVELANES_CROP_OFFSETS = {(1440, 2560, 3): 640, (660, 1570, 3): 180, (720, 1280, 3): 368}


@DATASETS.register_module()
class CurvelanesDataset(CulaneDataset):
    """mmdet3 port of the curvelane-branch ``CurvelanesDataset``.

    Each image is cropped from a resolution-specific top offset down to the
    bottom. The crop is recorded as ``crop_offset`` / ``crop_shape`` in
    ``metainfo``. The official batched head decodes with one global
    ``test_cfg``, so CurveLanes configs set ``ori_img_h=1, cut_height=0``
    (lanes stay in crop-normalized y) and ``CurvelanesMetric`` restores original
    coordinates per image. This reproduces the curvelane-branch detector, which
    overwrote ``test_cfg`` for every single-image batch.
    """

    def _crop(self, img_tmp):
        offset = CURVELANES_CROP_OFFSETS.get(tuple(img_tmp.shape))
        if offset is None:
            return None, None
        return img_tmp[offset:, ...].copy(), offset

    def prepare_train_img(self, idx):
        imgname = str(Path(self.img_prefix) / self.img_infos[idx])
        img_tmp = cv2.imread(imgname)
        ori_shape = img_tmp.shape
        img, offset = self._crop(img_tmp)
        if img is None:
            return None
        crop_shape = img.shape
        kps, id_classes, id_instances = self.load_labels(idx, -offset)
        eval_shape = (crop_shape[0] / ori_shape[0] * 224, 224)
        results = dict(
            filename=imgname,
            sub_img_name=self.img_infos[idx],
            img=img,
            gt_points=kps,
            id_classes=id_classes,
            id_instances=id_instances,
            img_shape=crop_shape,
            ori_shape=ori_shape,
            eval_shape=eval_shape,
            crop_shape=crop_shape,
            gt_masks=None,
        )
        if self.mask_paths[0]:
            mask = self.load_mask(idx)
            mask = mask[offset:, :, 0] if mask.ndim == 3 else mask[offset:, :]
            mask = np.clip(mask, 0, 1)
            assert mask.shape[:2] == crop_shape[:2]
            results["gt_masks"] = mask
        return self.pipeline(results)

    def prepare_test_img(self, idx):
        imgname = str(Path(self.img_prefix) / self.img_infos[idx])
        img_tmp = cv2.imread(imgname)
        ori_shape = img_tmp.shape
        img, offset = self._crop(img_tmp)
        if img is None:
            return None
        results = dict(
            filename=imgname,
            sub_img_name=self.img_infos[idx],
            img=img,
            gt_points=[],
            id_classes=[],
            id_instances=[],
            img_shape=img.shape,
            ori_shape=ori_shape,
            crop_offset=[0, offset],
            crop_shape=img.shape,
        )
        return self.pipeline(results)

    def load_labels(self, idx, offset_y=0):
        """Curvelane-branch ``CulaneDataset.load_labels`` (with ``offset_y``)."""
        anno_dir = str(Path(self.img_prefix).joinpath(self.annotations[idx]))
        return self._read_lines_txt(anno_dir, offset_y)

    @staticmethod
    def _read_lines_txt(path, offset_y=0):
        shapes = []
        with open(path, "r") as anno_f:
            for line in anno_f.readlines():
                coords = []
                coords_str = line.strip().split(" ")
                for i in range(len(coords_str) // 2):
                    coords.append(float(coords_str[2 * i]))
                    coords.append(float(coords_str[2 * i + 1]) + offset_y)
                if len(coords) > 3:
                    shapes.append(coords)
        return shapes, [1] * len(shapes), [i + 1 for i in range(len(shapes))]

    # -- round-trip helpers (probe) -------------------------------------------
    def results_with_labels(self, idx):
        imgname = str(Path(self.img_prefix) / self.img_infos[idx])
        img_tmp = cv2.imread(imgname)
        img, offset = self._crop(img_tmp)
        anno = str(Path(imgname).with_suffix("")) + ".lines.txt"
        kps, id_classes, id_instances = self._read_lines_txt(anno, -offset)
        return dict(filename=imgname, sub_img_name=self.img_infos[idx], img=img,
                    gt_points=kps, id_classes=id_classes, id_instances=id_instances,
                    img_shape=img.shape, ori_shape=img_tmp.shape,
                    crop_offset=[0, offset], crop_shape=img.shape)
